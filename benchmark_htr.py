"""Run a reproducible, CPU-only handwriting benchmark against a llama.cpp OCR model.

The input manifest is generated by download_benchmark_assets.py. It contains IAM
handwriting line images and their reference transcription. Output is JSON and CSV
so model comparisons remain inspectable rather than anecdotal.
"""
import argparse
import base64
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import secrets
import shutil
import socket
import subprocess
import sys
import time
import urllib.error
import urllib.request

ROOT = Path(__file__).resolve().parent


def normalized(text):
    return " ".join(text.replace("\n", " ").split()).casefold()


def distance(left, right):
    """Levenshtein distance with bounded memory."""
    if len(left) < len(right):
        left, right = right, left
    row = list(range(len(right) + 1))
    for index, char in enumerate(left, 1):
        next_row = [index]
        for column, other in enumerate(right, 1):
            next_row.append(min(next_row[-1] + 1, row[column] + 1,
                                row[column - 1] + (char != other)))
        row = next_row
    return row[-1]


def port():
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


def request(url, payload, key):
    body = json.dumps(payload).encode("utf-8")
    call = urllib.request.Request(url, data=body, headers={
        "Content-Type": "application/json", "Authorization": "Bearer " + key,
    })
    client = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    with client.open(call, timeout=900) as response:
        return json.load(response)


def await_server(url, key, process):
    client = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    deadline = time.monotonic() + 180
    while time.monotonic() < deadline:
        if process.poll() is not None:
            raise RuntimeError("llama-server stopped during startup")
        try:
            call = urllib.request.Request(url + "/health", headers={"Authorization": "Bearer " + key})
            with client.open(call, timeout=2) as response:
                if response.status == 200:
                    return
        except (OSError, urllib.error.URLError):
            time.sleep(0.5)
    raise TimeoutError("llama-server did not become ready within 3 minutes")


def start_server(binary, model, projector, server_port, key, threads, context, chat_template, log):
    command = [str(binary), "-m", str(model), "--mmproj", str(projector),
               "--host", "127.0.0.1", "--port", str(server_port), "-c", str(context),
               "-t", str(threads), "-ngl", "0", "--no-mmproj-offload", "--parallel", "1",
               "--no-webui", "--api-key", key]
    if chat_template:
        command.extend(["--chat-template", chat_template])
    flags = subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0
    return subprocess.Popen(command, stdout=log, stderr=subprocess.STDOUT, creationflags=flags)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--name", required=True, help="Name recorded in result files")
    parser.add_argument("--model", type=Path, required=True)
    parser.add_argument("--mmproj", type=Path, required=True)
    parser.add_argument("--prompt", default="OCR", help="Exact model prompt to benchmark")
    parser.add_argument("--chat-template", help="llama.cpp chat template required by a model")
    parser.add_argument("--threads", type=int, default=min(4, os.cpu_count() or 2))
    parser.add_argument("--context", type=int, default=4096)
    parser.add_argument("--max-tokens", type=int, default=512)
    parser.add_argument("--manifest", type=Path, default=ROOT / "benchmarks" / "iam-line-10.json")
    parser.add_argument("--output", type=Path)
    parser.add_argument("--binary", type=Path)
    args = parser.parse_args()
    if args.threads < 1 or args.context < 512 or args.max_tokens < 1:
        parser.error("threads, context, and max-tokens must be positive")
    if not args.model.is_file() or not args.mmproj.is_file() or not args.manifest.is_file():
        parser.error("model, projector, and manifest must exist")
    binary = args.binary or next((ROOT / "runtime").rglob("llama-server.exe"), None) or shutil.which("llama-server")
    if not binary:
        parser.error("llama-server was not found; pass --binary or run native setup")
    manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
    target = args.output or ROOT / "benchmarks" / "results" / (args.name + ".json")
    target.parent.mkdir(parents=True, exist_ok=True)
    server_port, key = port(), secrets.token_urlsafe(24)
    log_path = target.with_suffix(".engine.log")
    process = None
    started = time.monotonic()
    rows = []
    try:
        with log_path.open("w", encoding="utf-8") as log:
            process = start_server(binary, args.model, args.mmproj, server_port, key,
                                   args.threads, args.context, args.chat_template, log)
            url = f"http://127.0.0.1:{server_port}"
            await_server(url, key, process)
            for item in manifest["items"]:
                image = args.manifest.parent / item["file"]
                raw = base64.b64encode(image.read_bytes()).decode("ascii")
                payload = {"messages": [{"role": "user", "content": [
                    {"type": "text", "text": args.prompt},
                    {"type": "image_url", "image_url": {"url": "data:image/jpeg;base64," + raw}},
                ]}], "temperature": 0, "top_p": 1, "max_tokens": args.max_tokens, "stream": False}
                timer = time.monotonic()
                result = request(url + "/v1/chat/completions", payload, key)
                seconds = time.monotonic() - timer
                output = result["choices"][0]["message"].get("content", "")
                reference = item["text"]
                norm_output, norm_reference = normalized(output), normalized(reference)
                character_distance = distance(norm_output, norm_reference)
                word_distance = distance(norm_output.split(), norm_reference.split())
                rows.append({
                    "id": item["id"], "file": item["file"], "reference": reference,
                    "output": output, "seconds": seconds,
                    "cer": character_distance / max(1, len(norm_reference)),
                    "wer": word_distance / max(1, len(norm_reference.split())),
                    "finish_reason": result["choices"][0].get("finish_reason"),
                })
                print(f"{item['id']}: CER {rows[-1]['cer']:.3f}, WER {rows[-1]['wer']:.3f}, {seconds:.1f}s", flush=True)
    finally:
        if process and process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=15)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait()
    summary = {
        "name": args.name, "created": datetime.now(timezone.utc).isoformat(),
        "model": str(args.model), "mmproj": str(args.mmproj), "prompt": args.prompt,
        "chat_template": args.chat_template,
        "threads": args.threads, "context": args.context, "max_tokens": args.max_tokens,
        "manifest": str(args.manifest), "model_start_and_run_seconds": time.monotonic() - started,
        "mean_cer": sum(row["cer"] for row in rows) / max(1, len(rows)),
        "mean_wer": sum(row["wer"] for row in rows) / max(1, len(rows)),
        "mean_seconds": sum(row["seconds"] for row in rows) / max(1, len(rows)),
        "items": rows,
    }
    target.write_text(json.dumps(summary, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    csv_path = target.with_suffix(".csv")
    headers = ["id", "file", "seconds", "cer", "wer", "finish_reason", "reference", "output"]
    with csv_path.open("w", encoding="utf-8", newline="") as stream:
        import csv
        writer = csv.DictWriter(stream, fieldnames=headers)
        writer.writeheader()
        writer.writerows(rows)
    print(f"\n{args.name}: mean CER {summary['mean_cer']:.3f}, mean WER {summary['mean_wer']:.3f}, mean {summary['mean_seconds']:.1f}s")
    print(f"Saved {target} and {csv_path}")


if __name__ == "__main__":
    main()
